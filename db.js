// One tiny async database layer with two back-ends: PostgreSQL (production, DATABASE_URL) and SQLite (local dev / tests).
// The application writes portable SQL with `?` placeholders; this file adapts it. The only npm dependency is `pg`, loaded only when DATABASE_URL is set.
import path from 'node:path';

const PG_ID_TABLES = /^\s*INSERT INTO (reviews|officials|suggestions|feedback|join_requests|mod_log|mod_actions)\b/i;

export async function openDb({ url, file }) {
  if (url) return openPg(url);
  const { DatabaseSync } = await import('node:sqlite');
  const raw = new DatabaseSync(file);
  const wrap = sql => { const st = raw.prepare(sql); return {
    get: async (...a) => st.get(...a), all: async (...a) => st.all(...a),
    run: async (...a) => { const r = st.run(...a); return { lastInsertRowid: Number(r.lastInsertRowid), changes: Number(r.changes) }; } }; };
  const db = { dialect: 'sqlite', prepare: wrap, exec: async sql => { raw.exec(sql); }, close: async () => raw.close(),
    rnd: "hex(randomblob(6))", idCol: 'INTEGER PRIMARY KEY', bigint: 'INTEGER', pragma: 'PRAGMA journal_mode = WAL;' };
  return db;
}

async function openPg(url) {
  const pg = (await import('pg')).default;
  pg.types.setTypeParser(20, v => Number(v));        // int8 (COUNT, BIGINT millisecond timestamps) → number
  pg.types.setTypeParser(1700, v => parseFloat(v));  // numeric (AVG, SUM) → number
  const pool = new pg.Pool({ connectionString: url, max: 10, idleTimeoutMillis: 30000, statement_timeout: 10000 });
  pool.on('error', e => console.error('pg pool', e.message));
  const conv = sql => { let i = 0; return sql.replace(/\?/g, () => '$' + (++i)); };
  const wrap = sql => {
    const text = conv(sql), withId = PG_ID_TABLES.test(sql);
    const q = (a, t = text) => pool.query(t, a.map(x => (x === undefined ? null : x)));
    return {
      get: async (...a) => (await q(a)).rows[0],
      all: async (...a) => (await q(a)).rows,
      run: async (...a) => { const r = await q(a, withId ? text + ' RETURNING id' : text); return { lastInsertRowid: withId && r.rows[0] ? Number(r.rows[0].id) : 0, changes: r.rowCount }; },
    };
  };
  return { dialect: 'pg', prepare: wrap, exec: async sql => { await pool.query(sql); }, close: () => pool.end(),
    rnd: "substr(md5(random()::text), 1, 12)", idCol: 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', bigint: 'BIGINT', pragma: '' };
}
